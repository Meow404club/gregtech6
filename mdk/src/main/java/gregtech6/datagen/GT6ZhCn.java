/**
 * zh_cn lang, the A-wave small-unit companion of {@link GT6EnUs} (task p20-i18n-zhcn-provider,
 * ADR 2026-09-06-p20-i18n-zhcn-pipeline): zh_cn.json is GENERATED by this provider — the
 * hand-written-JSON red line forbids editing it directly. The translation VALUES come from the
 * committed reference table {@code /gregtech6/lang/zh_cn_ref.tsv} (produced by
 * {@code mdk/tools/gen_zhcn_ref.py} from the GT6 1.7.10 zh lang dump + a hand-translation
 * layer); the lang KEYS are derived here with the same single
 * {@link MaterialPrefixItem#snakeCase} implementation the en provider uses, so no second
 * snake_case algorithm exists (the Python side of the pipeline deliberately carries zero key
 * logic, ADR §1.1).
 *
 * <p>Four small-unit walks, each mirroring the exact {@link GT6EnUs} walk over the same
 * registry sources (per-key English fallback for skipped rows is vanilla's built-in
 * bilingual chain — LanguageManager.java:50-52 + ClientLanguage.java:29-46 — so zero
 * fallback code lives here):
 * <ol>
 * <li>{@link #addTabTitles()} — the creative tab titles: item prefix tabs
 *     ({@code itemGroup.gt6.<snake>} over {@link GTMaterialItems#tabPrefixes()}), block prefix
 *     tabs (over {@link GTMaterialBlocks#tabPrefixes()}) and the special MTE-category tabs,
 *     joined against the dump's {@code itemGroup.<camel>} family or the hand rows;</li>
 * <li>{@link #addPrefixTemplates()} — the {@code gt6.tagprefix.<snake>} display templates.
 *     The en provider emits all 467 OP prefixes; zh emits ONLY the hand-translated in-use set
 *     (status=hand direct rows, ADR §1.2 — the dump has no authoritative template face, and
 *     affix stripping would be statistical generalisation multiplied by 1273 materials). The
 *     parity test (GT6LangParityTest) structurally guarantees zh ⊆ en;</li>
 * <li>{@link #addMaterialNames()} — the {@code gt6.material.<snake>} small units, the exact
 *     {@link GT6EnUs#addMaterialNames()} walk (alias merge, first mID wins) joined against the
 *     dump's {@code gt.material.<Pascal>} family;</li>
 * <li>{@link #addMiscUnits()} — the atomic misc keys (tools, the eight atomic covers, the
 *     circuit selector tag + its configuration tooltip, the JEI coke-oven info page, the
 *     example chest, the two port fluids). The COMPOSED domains became B-wave template keys
 *     (p20-i18n-compose-wires/-rows); B1's face is {@link #addWireDomainUnits()} and B2's faces are
     *     {@link #addStoneVariantUnits()} + {@link #addRowDomainUnits()} — with the
     *     B-wave landed, the parity test's composed-domain negative assertions are
     *     EMPTY (the closeout state).
 * </ol>
 *
 * <p>Rows with status {@code review} (pure-ASCII dump values, suspected untranslated, e.g.
 * {@code gt.material.Magnite=Magnite}, tmp/gregtech.lang:5003) and rows with no reference
 * entry at all are skipped: the runtime falls back to English per key. The {@code mte} family
 * in the TSV is deliberately unused here — it is inert census data until the MTE ID-join
 * subface lands (arch card tasks.p20-arch-i18n).
 *
 * <p>Non-final on purpose: GT6LangParityTest records {@code add()} through a same-package
 * subclass (the GT6EnUsJeiInfoTest:52-64 posture) to collect both providers' key sets in a
 * bare JVM without a datagen run.
 */
public class GT6ZhCn extends LanguageProvider {

	/** Classpath location of the generated reference table (rides the jar, ADR §1.1). */
	static final String REFERENCE_RESOURCE = "/gregtech6/lang/zh_cn_ref.tsv";

	/** One reference row: the translation value and its pipeline status. */
	record RefRow(String value, String status) {
		/** review rows are suspected-untranslated dump entries — the provider skips them. */
		boolean skipped() {
			return "review".equals(status);
		}
	}

	private final Map<String, Map<String, RefRow>> reference;

	public GT6ZhCn(PackOutput output) {
		super(output, GT6DataGenerators.MOD_ID, "zh_cn");
		this.reference = loadReference();
	}

	@Override
	protected void addTranslations() {
		addTabTitles();
		addPrefixTemplates();
		addMaterialNames();
		addMiscUnits();
		addWireDomainUnits();
		addStoneVariantUnits(); // task p20-i18n-compose-rows
		addRowDomainUnits();    // task p20-i18n-compose-rows
	}

	/**
	 * The B2 stone-variant composed-display units (task p20-i18n-compose-rows): the 16
	 * {@code gt6.stone.variant.<snake>} position-param templates the
	 * {@code GTStoneBlock.getName} compose fills (the stone-name slot rides the
	 * gt6.material.* small units, zero new material debt). Wording = the dump's
	 * gt.stone.andesite.N family split (tmp/gregtech.lang:15246-15262).
	 */
	private void addStoneVariantUnits() {
		for (gregtech6.block.stone.StoneVariant tVariant : gregtech6.block.stone.StoneVariant.VALUES) {
			addDirect(tVariant.key());
		}
	}

	/**
	 * The B2 rows composed-display units (task p20-i18n-compose-rows): every family template
	 * + small unit the rows composes consume, walked from the SAME row tables and key
	 * derivations the en walk uses (the mirrors cannot drift on the KEY face; the VALUE face
	 * is the hand layer in the reference table). The atomic rows (brick burning box, heat
	 * transmitter, the two wood gearboxes) ride the same hand rows as their en literals.
	 */
	private void addRowDomainUnits() {
		// a word shared by several families is ONE unit key — dedup like the en walk's
		// addRowMatUnit (duplicate add would be a hard failure on the recording face)
		java.util.Set<String> tEmitted = new java.util.HashSet<>();
		
		addDirect(gregtech6.registry.GT6Kinetics.AXLE_DISPLAY_KEY);
		for (int tSize = 0; tSize < gregtech6.registry.GT6Kinetics.AXLE_SIZE_NAMES.length; tSize++) {
			addRowUnit(tEmitted, gregtech6.registry.GT6Kinetics.axleSizeUnitKey(tSize));
		}
		for (gregtech6.registry.GT6Kinetics.AxleSpec tSpec : gregtech6.registry.GT6Kinetics.AXLE_SPECS) {
			addRowUnit(tEmitted, gregtech6.registry.GT6Kinetics.axleMatUnitKey(tSpec));
		}
		// steam engines: the two templates + the row-material units
		addDirect(gregtech6.registry.GT6Kinetics.STEAM_DISPLAY_KEY);
		addDirect(gregtech6.registry.GT6Kinetics.STEAM_DISPLAY_STRONG_KEY);
		for (gregtech6.registry.GT6Kinetics.SteamEngineRow tRow : gregtech6.registry.GT6Kinetics.STEAM_ENGINES) {
			addRowUnit(tEmitted, gregtech6.registry.GT6Kinetics.steamMatUnitKey(tRow));
		}
		// diesel: the template + the row-material units
		addDirect(gregtech6.registry.GT6Kinetics.DIESEL_DISPLAY_KEY);
		for (gregtech6.registry.GT6Kinetics.DieselSpec tSpec : gregtech6.registry.GT6Kinetics.DIESEL_SPECS) {
			addRowUnit(tEmitted, gregtech6.registry.GT6Kinetics.dieselMatUnitKey(tSpec));
		}
		// burning boxes: the four templates + three family words + the row-material units
		addDirect(gregtech6.registry.GT6BurningBoxes.DISPLAY_KEY);
		addDirect(gregtech6.registry.GT6BurningBoxes.DISPLAY_DENSE_KEY);
		addDirect(gregtech6.registry.GT6BurningBoxes.DISPLAY_FLUIDBED_KEY);
		addDirect(gregtech6.registry.GT6BurningBoxes.DISPLAY_FLUIDBED_DENSE_KEY);
		addDirect(gregtech6.registry.GT6BurningBoxes.FAMILY_SOLID_UNIT_KEY);
		addDirect(gregtech6.registry.GT6BurningBoxes.FAMILY_LIQUID_UNIT_KEY);
		addDirect(gregtech6.registry.GT6BurningBoxes.FAMILY_GAS_UNIT_KEY);
		for (gregtech6.registry.GT6BurningBoxes.BurningBoxRow tRow : gregtech6.registry.GT6BurningBoxes.allRows()) {
			addRowUnit(tEmitted, gregtech6.registry.GT6BurningBoxes.matUnitKeyOf(tRow));
		}
		addDirect("block.gt6.brick_burning_box"); // the atomic Brick row (the whole-string key on both faces)
		// boilers: the two templates + the row-material units
		addDirect(gregtech6.registry.GT6Boilers.DISPLAY_KEY);
		addDirect(gregtech6.registry.GT6Boilers.DISPLAY_STRONG_KEY);
		for (gregtech6.registry.GT6Boilers.BoilerRow tRow : gregtech6.registry.GT6Boilers.allRows()) {
			addRowUnit(tEmitted, gregtech6.registry.GT6Boilers.matUnitKeyOf(tRow));
		}
		// machine tiers: the template + three machine words + three ordinal units
		addDirect(gregtech6.registry.GTMachines.MACHINE_DISPLAY_KEY);
		addDirect(gregtech6.registry.GTMachines.MACHINE_SHREDDER_UNIT_KEY);
		addDirect(gregtech6.registry.GTMachines.MACHINE_CRUSHER_UNIT_KEY);
		addDirect(gregtech6.registry.GTMachines.MACHINE_LATHE_UNIT_KEY);
		for (int tTier = 2; tTier <= 4; tTier++) {
			addDirect(gregtech6.registry.GTMachines.machineTierUnitKey(tTier));
		}
		// dryer/distillery: the two family templates + their row-material units
		addDirect(gregtech6.registry.GTMachines.DRYER_DISPLAY_KEY);
		addDirect(gregtech6.registry.GTMachines.DISTILLERY_DISPLAY_KEY);
		for (java.util.List<gregtech6.block.GTBasicMachineBlock.MachineRow> tRows
				: java.util.List.of(gregtech6.registry.GTMachines.DRYER_ROWS, gregtech6.registry.GTMachines.DISTILLERY_ROWS)) {
			for (gregtech6.block.GTBasicMachineBlock.MachineRow tRow : tRows) {
				addRowUnit(tEmitted, "gt6.row.mat." + tRow.matSlug());
			}
		}
		// large boiler + dense wall: the templates + the row-material units
		addDirect(gregtech6.registry.GTMultiBlocks.LARGE_BOILER_DISPLAY_KEY);
		addDirect(gregtech6.registry.GTMultiBlocks.DENSE_WALL_DISPLAY_KEY);
		for (gregtech6.registry.GTMultiBlocks.LargeBoilerRow tRow : gregtech6.registry.GTMultiBlocks.LARGE_BOILER_ROWS) {
			addRowUnit(tEmitted, gregtech6.registry.GTMultiBlocks.boilerMatUnitKeyOf(tRow));
		}
		for (gregtech6.registry.GTMultiBlocks.MultiblockPartRow tRow : gregtech6.registry.GTMultiBlocks.WALL_ROWS) {
			addRowUnit(tEmitted, gregtech6.registry.GTMultiBlocks.wallMatUnitKeyOf(tRow));
		}
		addDirect("block.gt6.heat_transmitter"); // the atomic transmitter (the whole-string key)
		// attachments: the two family templates + the attachment material words
		addDirect(gregtech6.registry.GT6Attachments.TAP_DISPLAY_KEY);
		addDirect(gregtech6.registry.GT6Attachments.FUNNEL_DISPLAY_KEY);
		for (gregtech6.registry.GT6Attachments.AttachmentRow tRow : gregtech6.registry.GT6Attachments.ROWS) {
			addRowUnit(tEmitted, gregtech6.registry.GT6Attachments.matUnitKeyOf(tRow));
		}
		// the two wood gearboxes (the atomic attachment extras, the Loader :1668/:1669 rows)
		addDirect("block.gt6.gearbox");
		addDirect("block.gt6.transformer_rotation");
	}

	/** Dedup across the row-family walks (the en addRowMatUnit mirror). */
	private void addRowUnit(java.util.Set<String> aEmitted, String aKey) {
		if (aEmitted.add(aKey)) addDirect(aKey);
	}

	/**
	 * The B1 wire-domain composed-display units (task p20-i18n-compose-wires): the five
	 * position-param templates the {@code GTWireBlock.displayNameOf} compose fills
	 * ({@code gt6.wire.display[.plain]} + the {@code gt6.wire.form.*} units), the two cover
	 * tier-ladder templates (the tier slot rides a plain literal — the CS.java:154 voltage
	 * numerals are proper nouns in BOTH locales, no small-unit keys) and the laser atomic
	 * exemption ({@code block.gt6.wire_laser}, the material-less family stays a whole-string
	 * key on both faces). All hand rows in the reference table — the zh wording evidence
	 * lives in the gen script's hand-layer comments. Emitted here so the en-side template
	 * walks (GT6EnUs.addElectricWires/addCovers) have their exact zh mirror: the composed
	 * zh wire names (e.g. "{@code 12×锡线缆}", "{@code 红色合金导线}") then cost ZERO new
	 * material translations on top of these eight units.
	 */
	private void addWireDomainUnits() {
		addDirect("gt6.wire.display");
		addDirect("gt6.wire.display.plain");
		addDirect("gt6.wire.form.wire");
		addDirect("gt6.wire.form.cable");
		addDirect("gt6.wire.form.wirelamp");
		addDirect("gt6.cover.conveyor.display");
		addDirect("gt6.cover.robot_arm.display");
		addDirect("block.gt6.wire_laser");
	}

	/** The item + block prefix tab titles and the special MTE-category tabs (mirror of GT6EnUs.addTabTitles/addBlockTabTitles + the tab literals). */
	private void addTabTitles() {
		for (OreDictPrefix tPrefix : GTMaterialItems.tabPrefixes()) {
			addFromFamily("itemgroup", tPrefix.mNameInternal,
				"itemGroup.gt6." + MaterialPrefixItem.snakeCase(tPrefix.mNameInternal));
		}
		for (OreDictPrefix tPrefix : GTMaterialBlocks.tabPrefixes()) {
			addFromFamily("itemgroup", tPrefix.mNameInternal,
				"itemGroup.gt6." + MaterialPrefixItem.snakeCase(tPrefix.mNameInternal));
		}
		// the special tabs have no dump face (the 1.7.10 dump's itemGroup family holds prefix
		// tabs only) — their titles ride the hand rows, keyed by the same literals/constants
		// the en walk uses so the faces cannot drift
		addDirect("itemGroup.gt6.chests");
		addDirect("itemGroup.gt6.machines");
		addDirect("itemGroup.gt6.multiblocks");
		addDirect("itemGroup.gt6.fluid_containers");
		addDirect("itemGroup.gt6.fluid_pipes");
		addDirect("itemGroup.gt6.electric_wires");
		addDirect(GTWires.REDSTONE_TAB_TITLE_KEY);
		addDirect(GTWires.LASER_TAB_TITLE_KEY);
		addDirect(GT6Tools.TAB_TITLE_KEY);
	}

	/** Only the hand-translated in-use prefix templates (mirror of GT6EnUs.addPrefixTemplates over OP.VALUES). */
	private void addPrefixTemplates() {
		Set<String> tSeen = new HashSet<>();
		for (OreDictPrefix tPrefix : OreDictPrefix.VALUES) {
			String tKey = "gt6.tagprefix." + MaterialPrefixItem.snakeCase(tPrefix.mNameInternal);
			if (!tSeen.add(tKey)) continue; // same snake_case-collision guard as the en walk
			addDirect(tKey);
		}
	}

	/** The material small units, the exact GT6EnUs.addMaterialNames walk (alias merge, first mID wins). */
	private void addMaterialNames() {
		Set<String> tSeen = new HashSet<>();
		for (OreDictMaterial tMaterial : MaterialRegistry.INSTANCE.MATERIAL_ARRAY) {
			if (tMaterial == null || tMaterial.mID < 0) continue;
			tMaterial = MaterialRegistry.INSTANCE.get(tMaterial); // alias merge, MaterialRegistry.java:182-185
			if (tMaterial == null || tMaterial.mID < 0 || tMaterial.mNameLocal == null) continue;
			String tKey = "gt6.material." + MaterialPrefixItem.snakeCase(tMaterial.mNameInternal);
			if (!tSeen.add(tKey)) continue; // first (lowest mID) definition wins
			addFromFamily("material", tMaterial.mNameInternal, tKey);
		}
	}

	/**
	 * The atomic misc units — every key here mirrors a GT6EnUs literal/constant and is part of
	 * NO composed domain (the B-wave cards shrink those; see the class javadoc). The cover
	 * names are the eight atomic covers; the conveyor/robot-arm tier ladders compose from the
	 * {@link #addWireDomainUnits()} templates since p20-i18n-compose-wires.
	 */
	private void addMiscUnits() {
		addDirect("item.gt6.crowbar");
		addDirect("item.gt6.cutter");
		addDirect("item.gt6.chisel");
		addDirect("item.gt6.cover_redstone_emitter");
		addDirect("item.gt6.cover_redstone_conductor_in");
		addDirect("item.gt6.cover_redstone_conductor_out");
		addDirect("item.gt6.cover_redstone_machine_switch");
		addDirect("item.gt6.cover_shutter");
		addDirect("item.gt6.cover_item_filter");
		addDirect("item.gt6.cover_auto_redstone_machine_switch");
		addDirect("item.gt6.cover_controller");
		addDirect("item.gt6.integrated_circuit");
		addDirect(GT6Circuits.TOOLTIP_KEY);
		addDirect(GT6JeiPlugin.INFO_KEY_COKE_OVEN);
		addDirect("block.gt6.example_chest");
		addDirect("fluid.gt6.iron_molten");
		addDirect("fluid.gt6.natural_gas");
	}

	/** Family join: derive nothing here beyond the caller's key — look the dump suffix up, skip absent/review rows. */
	private void addFromFamily(String aKind, String aSource, String aKey) {
		RefRow tRow = reference.get(aKind) == null ? null : reference.get(aKind).get(aSource);
		if (tRow != null && !tRow.skipped()) add(aKey, tRow.value());
	}

	/** Hand-row join: the key IS the final gt6 lang key (status=hand direct rows); skip absent/review rows. */
	private void addDirect(String aKey) {
		RefRow tRow = reference.get("direct") == null ? null : reference.get("direct").get(aKey);
		if (tRow != null && !tRow.skipped()) add(aKey, tRow.value());
	}

	/**
	 * Parses {@link #REFERENCE_RESOURCE}: {@code #}-comment and blank lines skipped, data rows
	 * are {@code kind<TAB>source<TAB>value<TAB>status}. Package-private static so the parity
	 * test reuses the single parse implementation (it asserts no hand row is orphaned).
	 */
	static Map<String, Map<String, RefRow>> loadReference() {
		Map<String, Map<String, RefRow>> rTable = new HashMap<>();
		InputStream tStream = GT6ZhCn.class.getResourceAsStream(REFERENCE_RESOURCE);
		if (tStream == null) throw new IllegalStateException("reference table missing on the classpath: " + REFERENCE_RESOURCE);
		try (BufferedReader tReader = new BufferedReader(new InputStreamReader(tStream, StandardCharsets.UTF_8))) {
			String tLine;
			while ((tLine = tReader.readLine()) != null) {
				if (tLine.isEmpty() || tLine.charAt(0) == '#') continue;
				String[] tFields = tLine.split("\t", -1);
				if (tFields.length != 4) throw new IllegalStateException("malformed reference row: " + tLine);
				rTable.computeIfAbsent(tFields[0], k -> new HashMap<>()).put(tFields[1], new RefRow(tFields[2], tFields[3]));
			}
		} catch (IOException aE) {
			throw new IllegalStateException("failed to read " + REFERENCE_RESOURCE, aE);
		}
		return rTable;
	}
}
